#!/usr/bin/env python3
"""elrsd: tools/elrsd_vectors.json -> src/elrs_vectors_gen.h.

Usage: python3 tools/vectors_to_h.py tools/elrsd_vectors.json > src/elrs_vectors_gen.h
(`make vectors` does exactly that, atomically). The generated header is checked in so that
`make` never needs python and `--selftest` runs without any file access. It contains ONLY
the TEST-UID d2:4c:3e:2e:fb:4d (phrase "elrsd selftest phrase 2026"); the generator refuses
any other UID so the real binding phrase can never leak into the tree.
"""
import json
import sys

TEST_UID = [0xD2, 0x4C, 0x3E, 0x2E, 0xFB, 0x4D]


def cstr(s):
    out = '"'
    for ch in s:
        if ch == '"':
            out += '\\"'
        elif ch == '\\':
            out += '\\\\'
        elif 32 <= ord(ch) < 127:
            out += ch
        else:
            out += '\\x%02x" "' % (ord(ch) & 0xFF)
    return out + '"'


def arr(vals, per_line=24, fmt=str):
    vals = list(vals)
    if not vals:
        return '{0}'
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append(', '.join(fmt(v) for v in vals[i:i + per_line]))
    return '{' + (',\n\t'.join(lines)) + '}'


def main():
    if len(sys.argv) != 2:
        sys.stderr.write(__doc__)
        return 2
    d = json.load(open(sys.argv[1]))
    if list(d['uid']['uid']) != TEST_UID:
        sys.stderr.write('vectors_to_h.py: refusing: JSON uid is not the TEST-UID d2:4c:3e:2e:fb:4d\n')
        return 3
    o = []
    w = o.append
    w('// GENERATED by tools/vectors_to_h.py from tools/elrsd_vectors.json - do not edit.')
    w('// elrsd codec selftest vectors (TEST-UID only, ELRS 3.3.1 exact). Included by')
    w('// src/elrs_codec_selftest.cpp only. Regenerate with `make vectors`.')
    w('#pragma once')
    w('#include <cstddef>')
    w('#include <cstdint>')
    w('')
    w('namespace elrsd {')
    w('namespace vec {')
    w('')
    # ---- uid ----
    u = d['uid']
    w('// ---- uid / binding phrase ----')
    w('static const char UID_PHRASE[] = %s;' % cstr(u['phrase']))
    w('static const char UID_MD5_INPUT[] = %s;' % cstr(u['md5_input']))
    w('static const uint8_t UID[6] = %s;' % arr(u['uid']))
    w('static const char UID_HEX[] = %s;' % cstr(u['uid_hex']))
    w('static const int UID_OTA_VERSION_ID = %d;' % u['ota_version_id'])
    w('static const uint32_t UID_FHSS_SEED = %du;' % u['fhss_seed'])
    w('static const uint16_t UID_CRC14_INIT = %d;' % u['crc14_init'])
    w('static const bool UID_IQ_INVERTED = %s;' % ('true' if u['iq_inverted'] else 'false'))
    w('struct uid_extra { const char *phrase; uint8_t uid[6]; };')
    w('static const uid_extra UID_EXTRA[%d] = {' % len(u['extra']))
    for e in u['extra']:
        w('\t{%s, %s},' % (cstr(e['phrase']), arr(e['uid'])))
    w('};')
    w('static const int N_UID_EXTRA = %d;' % len(u['extra']))
    w('')
    # ---- fhss ----
    f = d['fhss']
    w('// ---- FHSS 3.3.1 ----')
    w('static const int FHSS_N_CHANNELS = %d;' % f['n_channels'])
    w('static const int FHSS_SEQ_LEN = %d;' % f['seq_len'])
    w('static const int FHSS_SYNC_CHANNEL = %d;' % f['sync_channel'])
    w('static const double FHSS_FREQ_START_HZ = %r;' % float(f['freq_start_hz']))
    w('static const double FHSS_FREQ_STOP_HZ = %r;' % float(f['freq_stop_hz']))
    w('static const double FHSS_STEP_HZ = %r;' % float(f['step_hz']))
    w('static const uint32_t LCG_A = %du, LCG_C = %du; static const uint64_t LCG_M = %dull;' % (f['lcg']['a'], f['lcg']['c'], f['lcg']['m']))
    w('static const uint32_t LCG_FIRST16[16] = %s;' % arr(f['lcg']['first16_rng']))
    w('static const uint8_t FHSS_SEQUENCE[%d] = %s;' % (len(f['sequence']), arr(f['sequence'], 30)))
    w('static const int FHSS_SYNC_POSITIONS[%d] = %s;' % (len(f['sync_positions']), arr(f['sync_positions'])))
    w('static const int N_FHSS_SYNC_POSITIONS = %d;' % len(f['sync_positions']))
    w('static const double FHSS_FREQ_NOMINAL_HZ[80] = %s;' % arr(f['channel_freq_hz_nominal'], 8, lambda v: '%r' % float(v)))
    sx = f['sx1280']
    w('static const double SX1280_REG_STEP_HZ = %r;' % float(sx['reg_step_hz']))
    w('static const int64_t SX1280_START_REG = %d, SX1280_STOP_REG = %d, SX1280_SPREAD_REG_X256 = %d;' % (sx['start_reg'], sx['stop_reg'], sx['spread_reg_x256']))
    w('static const double SX1280_FREQ_ACTUAL_HZ[80] = %s;' % arr(sx['channel_freq_hz_actual'], 6, lambda v: '%r' % float(v)))
    w('')
    # ---- whitening / gray ----
    w('// ---- whitening / gray ----')
    w('static const uint8_t WHITENING_SEQ[%d] = %s;' % (len(d['whitening_seq']), arr(d['whitening_seq'], 30)))
    w('static const uint8_t GRAY_ENCODE[64] = %s;' % arr(d['gray']['encode'], 32))
    w('static const uint8_t GRAY_DECODE[64] = %s;' % arr(d['gray']['decode'], 32))
    w('')
    # ---- rates ----
    w('// ---- LI codec per rate ----')
    w('struct li_vector { uint8_t payload[13]; int ref; uint16_t symbols[42]; };')
    w('struct rate_vec {')
    w('\tint index, rate_hz, sf, cr_bits, payload_bytes, preamble_len, interval_us, hop_interval, tlm_denom_default;')
    w('\tbool verified;')
    w('\tint n_cw, n_coded, n_sym, n_slots, n_tail;')
    w('\tdouble frame_offset_symbols;')
    w('\tint dmin, t_correct;')
    w('\tconst int *K;                      // cr_bits entries')
    w('\tconst int *symbol_widths;          // n_sym entries')
    w('\tconst uint8_t *hamming_encode;     // 16 entries')
    w('\tconst int16_t *correct_table;      // 1 << cr_bits entries, -1 = uncorrectable')
    w('\tconst int *coded_bit_to_slot;      // n_coded entries')
    w('\tconst uint8_t *whitening_coded_bits; // n_coded entries')
    w('\tconst int *tail_slots;             // n_tail entries (stream order)')
    w('\tconst int *tail_copies;            // n_tail pairs (slot, source slot)')
    w('\tconst li_vector *vectors;')
    w('\tint n_vectors;')
    w('};')
    rates = sorted(d['rates'].items(), key=lambda kv: int(kv[0]))
    for idx, r in rates:
        p = 'R%s_' % idx
        w('static const int %sK[%d] = %s;' % (p, len(r['K']), arr(r['K'])))
        w('static const int %sWIDTHS[%d] = %s;' % (p, len(r['symbol_widths']), arr(r['symbol_widths'], 42)))
        w('static const uint8_t %sHENC[16] = %s;' % (p, arr(r['hamming_encode'])))
        w('static const int16_t %sCORRECT[%d] = %s;' % (p, len(r['correct_table']), arr(r['correct_table'], 32)))
        w('static const int %sCB2SLOT[%d] = %s;' % (p, len(r['coded_bit_to_slot']), arr(r['coded_bit_to_slot'], 32)))
        w('static const uint8_t %sWCODED[%d] = %s;' % (p, len(r['whitening_coded_bits']), arr(r['whitening_coded_bits'], 64)))
        ts = r['tail_slots']
        w('static const int %sTAIL_SLOTS[%d] = %s;' % (p, max(1, len(ts)), arr(ts)))
        tc = []
        for k, v in r['tail_copies'].items():
            tc += [int(k), int(v)]
        w('static const int %sTAIL_COPIES[%d] = %s;' % (p, max(1, len(tc)), arr(tc)))
        w('static const li_vector %sVECTORS[%d] = {' % (p, len(r['vectors'])))
        for v in r['vectors']:
            w('\t{%s, %d, %s},' % (arr(v['payload'], 13), v['ref'], arr(v['symbols'], 42)))
        w('};')
    w('static const rate_vec RATES[%d] = {' % len(rates))
    for idx, r in rates:
        p = 'R%s_' % idx
        w('\t{%d, %d, %d, %d, %d, %d, %d, %d, %d, %s, %d, %d, %d, %d, %d, %r, %d, %d, %sK, %sWIDTHS, %sHENC, %sCORRECT, %sCB2SLOT, %sWCODED, %sTAIL_SLOTS, %sTAIL_COPIES, %sVECTORS, %d},' % (
            int(idx), r['rate_hz'], r['sf'], r['cr_bits'], r['payload_bytes'], r['preamble_len'], r['interval_us'],
            r['hop_interval'], r['tlm_denom_default'], 'true' if r['verified'] else 'false',
            r['n_cw'], r['n_coded'], r['n_sym'], r['n_slots'], r['n_tail'], float(r['frame_offset_symbols']),
            r['dmin'], r['t_correct'], p, p, p, p, p, p, p, p, p, len(r['vectors'])))
    w('};')
    w('static const int N_RATES = %d;' % len(rates))
    w('')
    # ---- crc14 ----
    c = d['crc14']
    w('// ---- CRC-14 ----')
    w('static const uint16_t CRC14_POLY = 0x%04X;' % c['poly'])
    w('static const uint16_t CRC14_TABLE[256] = %s;' % arr(c['table'], 16))
    w('struct crc_example { uint8_t data[16]; int len; uint16_t init; uint16_t crc; };')
    w('static const crc_example CRC14_EXAMPLES[%d] = {' % len(c['examples']))
    for e in c['examples']:
        w('\t{%s, %d, %d, %d},' % (arr(e['data'] + [0] * (16 - len(e['data']))), len(e['data']), e['init'], e['crc']))
    w('};')
    w('static const int N_CRC14_EXAMPLES = %d;' % len(c['examples']))
    w('')
    # ---- ota4 rc ----
    w('// ---- OTA4 RC packets (3.3.1 Wide) ----')
    w('struct rc_vec {')
    w('\tint rate, hop_interval, tlm_denom, nonce;')
    w('\tuint16_t channels_crsf[16];')
    w('\tuint8_t packet[8];')
    w('\tint crc_high_injected;')
    w('\tint d_type, d_crc_high, d_crc_low;')
    w('\tuint16_t d_ch1_4[4];')
    w('\tint d_ch4_armed, d_switch_index, d_aux_channel, d_aux_value_raw, d_aux_crsf, d_tx_power, d_telem_bit; // -1 = absent')
    w('\tint residues[4]; int n_residues;')
    w('\tuint16_t expected_ch1_4[4];')
    w('};')
    w('static const rc_vec OTA4_RC[%d] = {' % len(d['ota4_rc']))
    for r in d['ota4_rc']:
        dd = r['decoded']
        res = r['crc_nonce_residues']
        w('\t{%d, %d, %d, %d, %s, %s, %d, %d, %d, %d, %s, %d, %d, %d, %d, %d, %d, %d, %s, %d, %s},' % (
            r['rate'], r['hop_interval'], r['tlm_denom'], r['nonce'], arr(r['channels_crsf'], 16), arr(r['packet']),
            r['crc_high_injected'], dd['type'], dd['crc_high'], dd['crc_low'], arr(dd['ch1_4_crsf']),
            dd['ch4_armed_bit'], dd['switch_index'], dd.get('aux_channel', -1), dd.get('aux_value_raw', -1),
            dd.get('aux_crsf', -1), dd.get('tx_power', -1), dd.get('telem_bit', -1),
            arr(res + [0] * (4 - len(res))), len(res), arr(r['expected_ch1_4_after_roundtrip'])))
    w('};')
    w('static const int N_OTA4_RC = %d;' % len(d['ota4_rc']))
    w('')
    # ---- ota4 sync ----
    w('// ---- OTA4 SYNC packets (3.3.1 layout) ----')
    w('struct sync_vec { int fhss_index, nonce, rate_index, new_tlm_ratio_field, tlm_denom, switch_enc_mode; uint8_t packet[8]; uint8_t uid345[3]; };')
    w('static const sync_vec OTA4_SYNC[%d] = {' % len(d['ota4_sync']))
    for s in d['ota4_sync']:
        w('\t{%d, %d, %d, %d, %d, %d, %s, %s},' % (s['fhss_index'], s['nonce'], s['rate_index'], s['new_tlm_ratio_field'],
                                                  s['tlm_denom'], s['switch_enc_mode'], arr(s['packet']), arr(s['uid345'])))
    w('};')
    w('static const int N_OTA4_SYNC = %d;' % len(d['ota4_sync']))
    w('')
    # ---- switch index / crsf ----
    w('static const int HYBRID_WIDE_SWITCH_INDEX[%d] = %s;' % (len(d['hybrid_wide_switch_index']), arr(d['hybrid_wide_switch_index'], 32)))
    w('struct pair_u32 { uint32_t a, b; };')
    for key in ['crsf_to_uint10', 'uint10_to_crsf', 'crsf_to_n128', 'crsf_to_n64', 'n_to_crsf127']:
        lst = d['crsf'][key]
        w('static const pair_u32 CRSF_%s[%d] = %s;' % (key.upper(), len(lst), arr(lst, 8, lambda p: '{%d, %d}' % (p[0], p[1]))))
        w('static const int N_CRSF_%s = %d;' % (key.upper(), len(lst)))
    w('')
    # ---- freerun ----
    fr = d['freerun']
    w('// ---- freerun ground truth ----')
    w('static const pair_u32 FREERUN_LOWBIAS32[%d] = %s;' % (len(fr['lowbias32']), arr(fr['lowbias32'], 3, lambda p: '{%du, %du}' % (p[0], p[1]))))
    w('static const int N_FREERUN_LOWBIAS32 = %d;' % len(fr['lowbias32']))
    w('struct freerun_ch { uint32_t tick; uint16_t ch[16]; };')
    w('static const freerun_ch FREERUN_CHANNELS[%d] = {' % len(fr['channels']))
    for e in fr['channels']:
        w('\t{%du, %s},' % (e['tick'], arr(e['channels'], 16)))
    w('};')
    w('static const int N_FREERUN_CHANNELS = %d;' % len(fr['channels']))
    w('')
    w('} // namespace vec')
    w('} // namespace elrsd')
    sys.stdout.write('\n'.join(o) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
